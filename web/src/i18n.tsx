export type MessageKey = keyof typeof messages.en;

function interpolate(template: string, values?: Record<string, string | number>) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(values?.[key] ?? `{{${key}}}`));
}

export function message(language: Language, key: MessageKey, values?: Record<string, string | number>) {
  return interpolate(messages[language][key] ?? messages.en[key] ?? key, values);
}

export function countLabel(language: Language, count: number, singular: MessageKey, plural: MessageKey) {
  return `${count} ${message(language, count === 1 ? singular : plural)}`;
}

interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey, values?: Record<string, string | number>) => string;
  count: (value: number, singular: MessageKey, plural: MessageKey) => string;
}

const LANGUAGE_STORAGE_KEY = 'patchpaw.language';
const I18nContext = createContext<I18nValue | undefined>(undefined);

function initialLanguage(): Language {
  if (typeof window === 'undefined') return 'zh-CN';
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return saved === 'en' || saved === 'zh-CN' ? saved : 'zh-CN';
  } catch {
    return 'zh-CN';
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  useEffect(() => {
    try { window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language); } catch { /* storage can be unavailable in privacy-restricted browsers */ }
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => message(language, key, values),
    count: (value, singular, plural) => countLabel(language, value, singular, plural),
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used within I18nProvider');
  return context;
}
